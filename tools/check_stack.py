#!/usr/bin/env python3
"""
tools/check_stack.py — Build-time eZ80 stack-usage guard.

Parses the `.su` files generated by `-fstack-usage` (ez80-clang / GCC) and
fails the build if any function allocates at least THRESHOLD bytes of stack
locals.

Background
----------
The TI-84 Plus CE eZ80 OS reserves only ~4 KB of stack for user programs.
PR #40 documented an emulator blind spot: CEmu runs on flat host memory and
does NOT trigger the OS stack watchdog, so a stack overflow appears as a
silent write into host memory on the emulator but as a "validating OS" RAM
clear on real hardware.  This script catches the class at build time so the
same bug cannot slip through again.

.su file format (ez80-clang / GCC -fstack-usage output)
---------------------------------------------------------
    <path>:<line>:<col>:<function-name>\t<bytes>\t<type>
or
    <path>:<line>:<function-name>\t<bytes>\t<type>

  <bytes>  — integer, bytes of stack locals for this function frame
  <type>   — one of: static | dynamic | dynamic,bounded

  "static"          : exact frame size known at compile time — always report
  "dynamic"         : VLAs / alloca, unbounded — always report
  "dynamic,bounded" : alloca with a compile-time upper bound — report using
                      the bound (treated as "static" here)

Usage
-----
    python tools/check_stack.py [options] [paths ...]

    paths      Directories or .su files to scan (default: search from CWD)

Options
    --threshold N    Fail if any frame >= N bytes (default: 1024)
    --warn-threshold W  Warn (but do not fail) if any frame >= W bytes
                         (default: 512)
    --exclude GLOB   Skip files matching this glob (repeatable)
    --dynamic-fail   Also fail on unbounded dynamic frames (default: warn only)
    --summary        Print only the violation count, not each violation
    --quiet          Print nothing on success
    --allow-empty    Permit missing, empty, or unparsable reports (default: fail)
    --expect-count N Require exactly N .su files (including with --allow-empty)

Exit codes
    0  No violations found (warnings are non-fatal)
    1  One or more threshold violations found
    2  Usage / argument error, empty scan, wrong file count, or invalid report
"""

from __future__ import annotations

import argparse
import fnmatch
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional


# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

@dataclass
class FrameEntry:
    source_file: str
    line: int
    function: str
    bytes_: int
    frame_type: str   # "static", "dynamic", "dynamic,bounded"
    su_file: str


@dataclass
class ScanResult:
    entries: List[FrameEntry] = field(default_factory=list)
    parse_errors: List[str] = field(default_factory=list)
    empty_su_files: List[str] = field(default_factory=list)
    su_files_scanned: int = 0


# ---------------------------------------------------------------------------
# Parser
# ---------------------------------------------------------------------------

def _parse_su_line(line: str, su_path: str) -> Optional[FrameEntry]:
    """Parse one line of a .su file.  Returns None for blank / comment lines."""
    line = line.rstrip('\n\r')
    if not line or line.startswith('#'):
        return None

    # Tab-separated: <location>\t<bytes>\t<type>
    parts = line.split('\t')
    if len(parts) != 3:
        return None

    location, bytes_str, frame_type = parts
    frame_type = frame_type.strip()

    try:
        bytes_ = int(bytes_str.strip())
    except ValueError:
        return None

    # Location is colon-separated: path:line[:col]:funcname
    # Split on ':' but keep the path intact (Windows paths may have drive letter)
    loc_parts = location.split(':')

    # Reconstruct Windows-style path: if part[0] is a single letter it's
    # the drive letter — join with part[1].
    if len(loc_parts) >= 2 and len(loc_parts[0]) == 1 and loc_parts[0].isalpha():
        # Windows path: C:/foo/bar.c:line[:col]:func
        if len(loc_parts) >= 4:
            src_file = loc_parts[0] + ':' + loc_parts[1]
            rest = loc_parts[2:]
        else:
            return None
    else:
        if len(loc_parts) >= 3:
            src_file = loc_parts[0]
            rest = loc_parts[1:]
        else:
            return None

    # rest is [line, col?, funcname] or [line, funcname]
    # funcname is always last; line is always first
    try:
        lineno = int(rest[0])
    except (ValueError, IndexError):
        lineno = 0

    func_name = rest[-1]

    return FrameEntry(
        source_file=src_file,
        line=lineno,
        function=func_name,
        bytes_=bytes_,
        frame_type=frame_type,
        su_file=su_path,
    )


def parse_su_file(su_path: str) -> tuple[List[FrameEntry], List[str]]:
    """Parse all entries in one .su file.  Returns (entries, errors)."""
    entries: List[FrameEntry] = []
    errors: List[str] = []
    try:
        with open(su_path, 'r', encoding='utf-8', errors='replace') as fh:
            for lineno, raw in enumerate(fh, 1):
                entry = _parse_su_line(raw, su_path)
                if entry is not None:
                    entries.append(entry)
                else:
                    stripped = raw.strip()
                    if stripped and not stripped.startswith('#'):
                        errors.append(f"{su_path}:{lineno}: unparsable line")
    except OSError as exc:
        errors.append(f"Cannot read {su_path}: {exc}")
    return entries, errors


# ---------------------------------------------------------------------------
# File discovery
# ---------------------------------------------------------------------------

def _should_exclude(path: str, excludes: List[str]) -> bool:
    for pat in excludes:
        if fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(os.path.basename(path), pat):
            return True
    return False


def find_su_files(search_paths: List[str], excludes: List[str]) -> List[str]:
    """Recursively find all .su files under the given paths."""
    result: List[str] = []
    for root_path in search_paths:
        p = Path(root_path)
        if p.is_file() and p.suffix == '.su':
            if not _should_exclude(str(p), excludes):
                result.append(str(p))
        elif p.is_dir():
            for su in p.rglob('*.su'):
                if not _should_exclude(str(su), excludes):
                    result.append(str(su))
        else:
            # Not a file or dir — skip silently (may be a glob pattern)
            pass
    return sorted({os.path.realpath(path) for path in result})


# ---------------------------------------------------------------------------
# Analysis
# ---------------------------------------------------------------------------

def scan(search_paths: List[str], excludes: List[str]) -> ScanResult:
    result = ScanResult()
    su_files = find_su_files(search_paths, excludes)
    result.su_files_scanned = len(su_files)
    for su_path in su_files:
        entries, errors = parse_su_file(su_path)
        result.entries.extend(entries)
        result.parse_errors.extend(errors)
        if not entries:
            result.empty_su_files.append(su_path)
    return result


def classify(
    entries: List[FrameEntry],
    threshold: int,
    warn_threshold: int,
    dynamic_fail: bool,
) -> tuple[List[FrameEntry], List[FrameEntry]]:
    """Returns (violations, warnings) where violations cause exit 1."""
    violations: List[FrameEntry] = []
    warnings: List[FrameEntry] = []

    for e in entries:
        is_dynamic_unbounded = (e.frame_type == 'dynamic')
        is_large = (e.bytes_ >= threshold)
        is_warn  = (warn_threshold <= e.bytes_ < threshold)

        if is_dynamic_unbounded and dynamic_fail:
            violations.append(e)
        elif is_large:
            violations.append(e)
        elif is_dynamic_unbounded or is_warn:
            warnings.append(e)

    return violations, warnings


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

def _frame_label(e: FrameEntry) -> str:
    type_tag = {
        'static': 'static',
        'dynamic,bounded': 'bounded',
        'dynamic': 'DYNAMIC',
    }.get(e.frame_type, e.frame_type)
    return (
        f"  {e.bytes_:>6} B [{type_tag:<8}]  "
        f"{e.function}  "
        f"({os.path.basename(e.source_file)}:{e.line})"
    )


def _print_evidence_warnings(result: ScanResult) -> None:
    """Print --allow-empty evidence problems to stderr (never suppressed)."""
    for e_msg in result.parse_errors:
        print(f"  PARSE ERROR: {e_msg}", file=sys.stderr)
    for su_path in result.empty_su_files:
        print(f"  EMPTY REPORT: {su_path}: no function frame entries",
              file=sys.stderr)


def report(
    result: ScanResult,
    violations: List[FrameEntry],
    warnings: List[FrameEntry],
    threshold: int,
    warn_threshold: int,
    summary_only: bool,
    quiet: bool,
) -> None:
    # Evidence problems reach this point only under --allow-empty.  Always
    # print them to stderr, even with --quiet, so they are never silent.
    _print_evidence_warnings(result)

    if quiet and not violations and not warnings:
        return

    total = len(result.entries)
    print(f"check_stack: scanned {result.su_files_scanned} .su file(s), "
          f"{total} function frame(s)")

    if warnings and not summary_only:
        print(f"\n  WARNINGS (>= {warn_threshold} B, < {threshold} B):")
        for e in sorted(warnings, key=lambda x: -x.bytes_):
            print(_frame_label(e))

    if violations:
        print(
            f"\n  VIOLATIONS (frame >= {threshold} B) — BUILD BLOCKED:\n",
            file=sys.stderr,
        )
        for e in sorted(violations, key=lambda x: -x.bytes_):
            print(_frame_label(e), file=sys.stderr)
        print(
            f"\n  {len(violations)} violation(s) found.  "
            f"Stack locals must stay under {threshold} B per function.\n"
            f"  (eZ80 OS stack is ~4 KB; combined frames on the call chain "
            f"crash with 'validating OS' RAM-clear on hardware)\n",
            file=sys.stderr,
        )
    elif not quiet:
        print(f"  OK — no frame exceeds {threshold} B")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description='Check ez80-clang -fstack-usage .su files for large frames.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        'paths', nargs='*', default=['.'],
        help='Directories or .su files to scan (default: current directory)',
    )
    p.add_argument(
        '--threshold', type=int, default=1024, metavar='N',
        help='Fail if any frame >= N bytes (default: 1024)',
    )
    p.add_argument(
        '--warn-threshold', type=int, default=512, metavar='W',
        help='Warn (non-fatal) if any frame >= W bytes (default: 512)',
    )
    p.add_argument(
        '--exclude', action='append', default=[], metavar='GLOB',
        help='Skip .su files matching this glob (repeatable)',
    )
    p.add_argument(
        '--dynamic-fail', action='store_true',
        help='Also fail on unbounded dynamic frames (default: warn only)',
    )
    p.add_argument(
        '--summary', action='store_true',
        help='Print only counts, not each violation',
    )
    p.add_argument(
        '--quiet', action='store_true',
        help='Print nothing on success',
    )
    p.add_argument(
        '--allow-empty', action='store_true',
        help='Permit missing, empty, or unparsable reports',
    )
    p.add_argument(
        '--expect-count', type=int, metavar='N',
        help='Require exactly N .su files (even with --allow-empty)',
    )
    return p


def main(argv: Optional[List[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.threshold <= 0:
        print("error: --threshold must be positive", file=sys.stderr)
        return 2

    if args.expect_count is not None and args.expect_count < 0:
        print("error: --expect-count must be non-negative", file=sys.stderr)
        return 2

    result = scan(args.paths, args.exclude)
    if ((not result.su_files_scanned and not args.allow_empty) or
            ((result.parse_errors or result.empty_su_files) and not args.allow_empty) or
            (args.expect_count is not None and
             result.su_files_scanned != args.expect_count)):
        print(f"check_stack: scanned {result.su_files_scanned} .su file(s), "
              f"{len(result.entries)} function frame(s)")
        if not result.su_files_scanned and not args.allow_empty:
            print("error: no .su files found; build with -fstack-usage or "
                  "pass --allow-empty", file=sys.stderr)
        if args.expect_count is not None and result.su_files_scanned != args.expect_count:
            print(f"error: expected {args.expect_count} .su file(s), "
                  f"found {result.su_files_scanned}; stale or legacy reports under obj/? "
                  "run 'make clean' and rebuild", file=sys.stderr)
        if not args.allow_empty:
            for error in result.parse_errors:
                print(f"error: {error}", file=sys.stderr)
            for su_path in result.empty_su_files:
                print(f"error: {su_path}: no function frame entries", file=sys.stderr)
        else:
            _print_evidence_warnings(result)
        return 2
    violations, warnings = classify(
        result.entries,
        args.threshold,
        args.warn_threshold,
        args.dynamic_fail,
    )
    report(
        result, violations, warnings,
        args.threshold, args.warn_threshold,
        args.summary, args.quiet,
    )
    return 1 if violations else 0


if __name__ == '__main__':
    sys.exit(main())
